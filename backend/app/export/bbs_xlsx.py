"""Bar Bending Schedule workbook.

Reproduces the layout of Avighna's hand-made
'Measurement Sheet_<Level> Reinforcement.xlsx' (Summary + one tab per
category) with LIVE formulas, so the senior engineers can audit every
cut length and weight exactly the way they always have:

* Beam tab      -> columns of the reference '14th  Beam' sheet
                   (G description, I span, J dia, K spacing, L bars, M/N/O/P = a/b/c/lap,
                    Q bend corners, R = SUM(M:P)-(J*Q*0.6/1000),
                    S.. = IF(J=$S$8, C*L*R*$S$9, " - "))
* Slab / NSW / Staircase tabs -> columns of the reference '14th slab' sheet
                   (H dia, I..O = a..g, P corners, Q cut length, R spacing,
                    S bars per member, T = S*C(member header), U.. = IF(H=$U$11, Q*T*$U$12, " - "))
* Column tab    -> columns of the reference '13th To 14th Column' sheet
                   (C/D/E = L/B/D, G nos, H dia, I..O = a..g, P corners, Q cut length,
                    R spacing, S rings per layer, T bars per member, U = G*T,
                    V.. = IF(V$7=$H, $U*$Q*V$8, 0))

Every category tab ends with a diameter-wise total row that the Summary
tab references with cross-sheet formulas (divided by 1000 -> tons).
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from openpyxl import Workbook
from openpyxl.worksheet.worksheet import Worksheet

from app.engine.bbs import compute_bbs
from app.export._style import (
    BORDER_BOTTOM_MEDIUM, BORDER_MEDIUM, BORDER_THIN, BRAND_RED, CENTER, FMT_INT, FMT_KG,
    FMT_LEN, FMT_PCT, FMT_TON, GREY_FILL, LEFT, LEFT_TOP, MID_FILL, PALE_FILL, RIGHT, WHITE,
    blank_if_zero, col, est_row_height, fill, font, header, info, merge, print_setup, put,
    qs, safe_sheet_name, set_heights, set_widths, style_cells, tab_color,
)
from app.models.schemas import BarRow, BBSResult, JobRecord, MemberResult, Standards

KIND_ORDER = ["beam", "slab", "column", "wall", "stair"]
TAB_LABEL = {"beam": "Beam", "slab": "Slab", "column": "Column", "wall": "NSW", "stair": "Staircase"}
LOCATION_LABEL = {
    "beam": "Beam",
    "slab": "Floor Slab",
    "column": "Column",
    "wall": "Non Structural Wall",
    "stair": "Staircase",
}
AUDIT_HEADER = "Remarks / Formula"


@dataclass
class _TabInfo:
    kind: str
    name: str
    kg_row: int                # row holding the diameter-wise SUM in kg
    dia_cols: Dict[int, str]   # dia (mm) -> column letter
    member_count: int


@dataclass
class _Ctx:
    job: JobRecord
    result: BBSResult
    std: Standards
    dias: List[int]
    level: str
    level_short: str
    spec_by_id: Dict[str, object]
    date_str: str

    def summary_label(self, kind: str) -> str:
        if kind == "beam":
            return f"{self.level} Beam".strip()
        if kind == "slab":
            return f"{self.level} Slab".strip()
        base = {"column": "Column", "wall": "NSW", "stair": "Staircase"}[kind]
        return f"{base} ({self.level})" if self.level else base


# --------------------------------------------------------------------------- #
# public entry point
# --------------------------------------------------------------------------- #
def write_bbs_workbook(job: JobRecord, path: Path) -> Path:
    """Write the BBS workbook for a structural job and return the path."""
    result = job.result
    if result is None:
        if not job.members:
            raise ValueError("Job has no BBS result and no members to compute one from")
        result = compute_bbs(job.members, job.standards, job.level)
    std = result.standards or job.standards

    dias = list(std.diameters_in_summary)
    for m in result.members:
        for r in m.rows:
            if r.dia_mm not in dias:
                dias.append(r.dia_mm)
    dias.sort()

    ctx = _Ctx(
        job=job, result=result, std=std, dias=dias,
        level=(job.level or "").strip(),
        level_short=_short_level(job.level or ""),
        spec_by_id={getattr(m, "id", None): m for m in job.members},
        date_str=datetime.now().strftime("%d-%b-%Y"),
    )

    wb = Workbook()
    wb.properties.creator = "Avighna BOQ"
    wb.properties.title = f"{job.project_name} - {job.level} - Bar Bending Schedule"
    wb.properties.subject = "Bar Bending Schedule"
    wb.properties.description = f"Generated by Avighna BOQ for job {job.id}"

    summary_ws = wb.active
    summary_ws.title = "Summary"

    tabs: List[_TabInfo] = []
    by_kind: Dict[str, List[MemberResult]] = {}
    for m in result.members:
        by_kind.setdefault(m.kind, []).append(m)
    for kind in KIND_ORDER:
        members = by_kind.get(kind) or []
        if not members:
            continue
        if kind == "beam":
            tabs.append(_write_beam_tab(wb, ctx, members))
        elif kind == "column":
            tabs.append(_write_column_tab(wb, ctx, members))
        else:
            tabs.append(_write_slab_style_tab(wb, ctx, kind, members))

    _write_summary(summary_ws, ctx, tabs)
    _write_extraction_log(wb, ctx)

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def _short_level(level: str) -> str:
    """'14th Floor' -> '14th' (the reference tab names drop the word Floor)."""
    s = re.sub(r"\s*\b(floor|level|storey|story)\b\s*$", "", level.strip(), flags=re.I)
    return s.strip()


def _tab_name(wb: Workbook, ctx: _Ctx, kind: str) -> str:
    return safe_sheet_name(f"{ctx.level_short} {TAB_LABEL[kind]}".strip(), wb.sheetnames)


def _dims(kind: str, spec) -> Tuple[Optional[float], Optional[float], Optional[float]]:
    if spec is None:
        return None, None, None
    try:
        if kind == "beam":
            return spec.span_m, spec.width_m, spec.depth_m
        if kind == "slab":
            return spec.length_m, spec.width_m, spec.thickness_m
        if kind == "column":
            return spec.length_m, spec.width_m, spec.height_m
        if kind == "wall":
            return spec.length_m, spec.thickness_m, spec.height_m
        if kind == "stair":
            f = spec.flights[0] if spec.flights else None
            return (f.going_m, f.width_m, f.waist_m) if f else (None, None, None)
    except AttributeError:
        pass
    return None, None, None


def _bars_summary(m: MemberResult) -> str:
    """'2.450 x 230 x 750 | Bot 2-T20 | Top 2-T20' -> 'Bot 2-T20 | Top 2-T20'."""
    parts = [p.strip() for p in (m.size_label or "").split("|")]
    return " | ".join(parts[1:]) if len(parts) > 1 else (m.size_label or "")


def _warnings_text(m: MemberResult) -> str:
    return "; ".join(m.warnings) if m.warnings else ""


def _per_layer(row: BarRow) -> int:
    """Column ties: recover the 'rings per layer' factor from the engine trace (default 1)."""
    m = re.search(r"\+ 1\) x (\d+) =", row.formula or "")
    return int(m.group(1)) if m else 1


def _project_lines(ws: Worksheet, ctx: _Ctx, first_row: int, last_col: str) -> None:
    job = ctx.job
    name = f"Name of Work: {job.project_name}"
    if job.location:
        name += f", {job.location}"
    put(ws, f"A{first_row}", name, font=font(14), alignment=LEFT)
    put(ws, f"A{first_row + 1}", f"Contractor Name : {job.contractor or '-'}", font=font(14), alignment=LEFT)
    put(ws, f"A{first_row + 2}", job.work_description, font=font(14), alignment=LEFT)
    set_heights(ws, {first_row: 18.75, first_row + 1: 18.75, first_row + 2: 18.75})


def _refs(ctx: _Ctx) -> str:
    return ", ".join(ctx.job.drawing_refs) if ctx.job.drawing_refs else "-"


def _data_row_style(ws: Worksheet, row: int, first_col: int, last_col: int, *, size: float = 10) -> None:
    style_cells(ws, f"{col(first_col)}{row}:{col(last_col)}{row}",
                font=font(size), border=BORDER_THIN, alignment=CENTER)


def _member_header_style(ws: Worksheet, row: int, first_col: int, last_col: int) -> None:
    style_cells(ws, f"{col(first_col)}{row}:{col(last_col)}{row}",
                font=font(10, bold=True), border=BORDER_THIN, alignment=CENTER, fill=PALE_FILL)


def _audit_cell(ws: Worksheet, ref: str, text: str) -> None:
    put(ws, ref, text or None, font=font(8, color="595959"), alignment=LEFT_TOP, border=BORDER_THIN)


