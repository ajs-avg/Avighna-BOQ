# Beam tab (reference: '14th  Beam')
# --------------------------------------------------------------------------- #
def _write_beam_tab(wb: Workbook, ctx: _Ctx, members: List[MemberResult]) -> _TabInfo:
    ws = wb.create_sheet(_tab_name(wb, ctx, "beam"))
    dias = ctx.dias
    first = 19  # S
    dcol = {d: col(first + i) for i, d in enumerate(dias)}
    last = col(first + len(dias) - 1)
    last_i = first + len(dias) - 1
    rem = col(last_i + 1)

    widths = {
        "A": 5, "B": 14, "C": 5, "D": 7.5, "E": 7, "F": 7, "G": 42, "H": 9, "I": 7.5, "J": 5.5,
        "K": 9, "L": 7.5, "M": 12, "N": 10, "O": 12, "P": 9, "Q": 9.5, "R": 10.5,
    }
    for d in dias:
        widths[dcol[d]] = 11.5
    widths[rem] = 58
    set_widths(ws, widths)

    _project_lines(ws, ctx, 1, rem)

    # ---- title block rows 4-6 (medium borders, Arial 12 bold - like the reference)
    info(ws, "A4:B4", "DRAWN BY :", alignment=LEFT)
    info(ws, "C4:F4", ctx.job.drawn_by or "-", bold=False)
    info(ws, "G4", "LD")
    info(ws, "H4", "Shape Of Bar")
    info(ws, "I4:J4", "Cover")
    info(ws, "K4", "LOCATION")
    info(ws, f"L4:R4", LOCATION_LABEL["beam"], bold=False)
    info(ws, "S4:T4", "Dwg No:")
    info(ws, f"U4:{last}4", _refs(ctx), bold=False, alignment=LEFT, size=10)
    info(ws, "A5:B5", "Date :", alignment=LEFT)
    info(ws, "C5:F5", ctx.date_str, bold=False)
    info(ws, "G5", ctx.std.ld_factor, number_format="0")
    info(ws, "H5", None)
    info(ws, "I5:J5", ctx.std.cover_beam_mm, number_format="0")
    info(ws, "K5", "LEVEL")
    info(ws, "L5:R5", ctx.level or "-", bold=False)
    info(ws, "S5:T5", "Job No:")
    info(ws, f"U5:{last}5", ctx.job.id, bold=False, size=10)
    info(ws, "A6:B6", None)
    info(ws, "C6:F6", "Size Of Member")
    info(ws, "G6:J6", None)
    info(ws, "K6:R6", "Length Calculation")
    info(ws, f"S6:{last}6", "WEIGHT CALCULATIONS")
    info(ws, f"{rem}4:{rem}6", "Audit trail (engine trace)", bold=False, size=10)
    set_heights(ws, {4: 30, 5: 20, 6: 18})

    # ---- column header rows 7-9 (brand red)
    header(ws, "A7:A9", "Sr. No.")
    header(ws, "B7:B9", "Description")
    header(ws, "C7:C9", "No")
    header(ws, "D7:D9", "L / A")
    header(ws, "E7:E9", "B / W")
    header(ws, "F7:F9", "D / H")
    header(ws, "G7:G9", "Location / Description of Bar")
    header(ws, "H7:H9", "Shape")
    header(ws, "I7:I9", "Span")
    header(ws, "J7:J9", "Dia")
    header(ws, "K7:K9", "Spacing (m)")
    header(ws, "L7:L9", "No. of Bars")
    header(ws, "M7:M9", "Anchorage (a)")
    header(ws, "N7:N9", "Straight (b)")
    header(ws, "O7:O9", "Anchorage (c)")
    header(ws, "P7:P9", "Lap (d)")
    header(ws, "Q7:Q9", "Bend Deduction Corners")
    header(ws, "R7:R9", "Length of one Bar")
    header(ws, f"S7:{last}7", "DIAMETERS")
    for d in dias:
        header(ws, f"{dcol[d]}8", d, number_format="0")
        put(ws, f"{dcol[d]}9", ctx.std.unit_weight(d), font=font(10, bold=True), fill=MID_FILL,
            border=BORDER_THIN, alignment=CENTER, number_format="0.000")
    header(ws, f"{rem}7:{rem}9", AUDIT_HEADER)
    set_heights(ws, {7: 48, 8: 18, 9: 18})

    # ---- data
    r = 11  # row 10 left blank like the reference; sums start at 10
    sr = 0
    for m in members:
        sr += 1
        hdr = r
        spec = ctx.spec_by_id.get(m.member_id)
        L, B, D = _dims("beam", spec)
        _member_header_style(ws, hdr, 1, last_i + 1)
        put(ws, f"A{hdr}", sr)
        put(ws, f"B{hdr}", m.tag)
        put(ws, f"C{hdr}", m.nos)
        put(ws, f"D{hdr}", L, number_format=FMT_LEN)
        put(ws, f"E{hdr}", B, number_format=FMT_LEN)
        put(ws, f"F{hdr}", D, number_format=FMT_LEN)
        put(ws, f"G{hdr}", _bars_summary(m) or m.size_label, alignment=LEFT)
        _audit_cell(ws, f"{rem}{hdr}", _warnings_text(m))
        style_cells(ws, f"{rem}{hdr}", fill=PALE_FILL)
        r += 1
        for row in m.rows:
            _data_row_style(ws, r, 1, last_i + 1)
            put(ws, f"C{r}", row.members, number_format=FMT_INT)
            put(ws, f"G{r}", row.description, alignment=LEFT)
            put(ws, f"H{r}", row.shape)
            put(ws, f"I{r}", blank_if_zero(row.span_m), number_format=FMT_LEN)
            put(ws, f"J{r}", row.dia_mm, number_format=FMT_INT)
            put(ws, f"K{r}", (row.spacing_mm / 1000.0) if row.spacing_mm else None, number_format=FMT_LEN)
            put(ws, f"L{r}", row.bars_per_member, number_format=FMT_INT)
            put(ws, f"M{r}", blank_if_zero(row.a), number_format=FMT_LEN)
            put(ws, f"N{r}", blank_if_zero(row.b), number_format=FMT_LEN)
            put(ws, f"O{r}", blank_if_zero(row.c), number_format=FMT_LEN)
            put(ws, f"P{r}", blank_if_zero(row.d + row.e + row.f + row.g), number_format=FMT_LEN)
            put(ws, f"Q{r}", blank_if_zero(row.bend_corners), number_format=FMT_INT)
            put(ws, f"R{r}", f"=SUM(M{r}:P{r})-(J{r}*Q{r}*0.6/1000)", number_format=FMT_LEN)
            for d in dias:
                c = dcol[d]
                put(ws, f"{c}{r}", f'=IF(J{r}=${c}$8,C{r}*L{r}*R{r}*${c}$9," - ")', number_format=FMT_KG)
            _audit_cell(ws, f"{rem}{r}", row.formula)
            ws.row_dimensions[r].height = max(
                est_row_height(row.description, widths["G"]),
                est_row_height(row.formula, widths[rem], base=12, line=10.5),
            )
            r += 1
        r += 1  # spacer row between members

    # ---- totals
    tr = r
    merge(ws, f"P{tr}:R{tr}", " Wt In Kgs", font=font(10, bold=True), border=BORDER_THIN, alignment=CENTER)
    merge(ws, f"P{tr + 1}:R{tr + 1}", " Wt In Tons", font=font(10, bold=True), border=BORDER_THIN, alignment=CENTER)
    merge(ws, f"P{tr + 2}:R{tr + 2}", "Total Wt In Tons", font=font(10, bold=True), border=BORDER_THIN, alignment=CENTER)
    merge(ws, f"P{tr + 3}:R{tr + 3}", "Total (kg)", font=font(10, bold=True), border=BORDER_THIN, alignment=CENTER)
    for d in dias:
        c = dcol[d]
        put(ws, f"{c}{tr}", f"=SUM({c}10:{c}{tr - 1})", font=font(10, bold=True), border=BORDER_THIN,
            alignment=CENTER, number_format=FMT_KG, fill=GREY_FILL)
        put(ws, f"{c}{tr + 1}", f"={c}{tr}/1000", font=font(10, bold=True), border=BORDER_THIN,
            alignment=CENTER, number_format=FMT_TON)
    merge(ws, f"S{tr + 2}:{last}{tr + 2}", f"=SUM(S{tr + 1}:{last}{tr + 1})", font=font(12, bold=True),
          border=BORDER_THIN, alignment=CENTER, number_format=FMT_TON, fill=PALE_FILL)
    merge(ws, f"S{tr + 3}:{last}{tr + 3}", f"=SUM(S{tr}:{last}{tr})", font=font(10, bold=True),
          border=BORDER_THIN, alignment=CENTER, number_format=FMT_KG)

    ws.freeze_panes = "A10"
    print_setup(ws, title_rows="7:9")
    return _TabInfo("beam", ws.title, tr, dcol, len(members))


