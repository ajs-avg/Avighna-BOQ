def _write_extraction_log(wb: Workbook, ctx: _Ctx) -> None:
    ws = wb.create_sheet(safe_sheet_name("Extraction Log", wb.sheetnames))
    cols = ["Sr", "Member tag", "Kind", "Nos", "Source sheet", "Confidence", "Evidence", "Warnings",
            "Remarks", "Weight (kg)"]
    widths = {"A": 5, "B": 14, "C": 10, "D": 6, "E": 18, "F": 11, "G": 60, "H": 45, "I": 30, "J": 12}
    set_widths(ws, widths)
    merge(ws, "A1:J1", f"Extraction log  |  {ctx.job.project_name}  |  {ctx.level}",
          font=font(12, bold=True), alignment=LEFT)
    for i, name in enumerate(cols, 1):
        header(ws, f"{col(i)}2", name)
    ws.row_dimensions[2].height = 20

    results = {m.member_id: m for m in ctx.result.members}
    r = 3
    sr = 0
    seen = set()
    for spec in ctx.job.members:
        sr += 1
        res = results.get(getattr(spec, "id", ""))
        seen.add(getattr(spec, "id", ""))
        _log_row(ws, r, sr, spec.tag, spec.kind, spec.nos, spec.source_sheet, spec.confidence,
                 spec.evidence, res.warnings if res else [], spec.remarks, res.weight_kg if res else None, widths)
        r += 1
    for res in ctx.result.members:
        if res.member_id in seen:
            continue
        sr += 1
        _log_row(ws, r, sr, res.tag, res.kind, res.nos, None, res.confidence, [], res.warnings, None,
                 res.weight_kg, widths)
        r += 1
    ws.freeze_panes = "A3"
    print_setup(ws, title_rows="2:2")


def _log_row(ws, r, sr, tag, kind, nos, source_sheet, confidence, evidence, warnings, remarks, weight, widths):
    style_cells(ws, f"A{r}:J{r}", font=font(9), border=BORDER_THIN, alignment=LEFT_TOP)
    put(ws, f"A{r}", sr, alignment=CENTER)
    put(ws, f"B{r}", tag)
    put(ws, f"C{r}", kind)
    put(ws, f"D{r}", nos, alignment=CENTER)
    put(ws, f"E{r}", source_sheet or "-")
    put(ws, f"F{r}", confidence, number_format=FMT_PCT, alignment=CENTER)
    ev = " | ".join(evidence) if evidence else ""
    wn = "; ".join(warnings) if warnings else ""
    put(ws, f"G{r}", ev or None)
    put(ws, f"H{r}", wn or None)
    put(ws, f"I{r}", remarks or None)
    put(ws, f"J{r}", weight, number_format=FMT_KG, alignment=CENTER)
    ws.row_dimensions[r].height = max(
        est_row_height(ev, widths["G"]), est_row_height(wn, widths["H"]), est_row_height(remarks, widths["I"]),
    )
