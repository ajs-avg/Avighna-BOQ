def _write_slab_style_tab(wb: Workbook, ctx: _Ctx, kind: str, members: List[MemberResult]) -> _TabInfo:
    ws = wb.create_sheet(_tab_name(wb, ctx, kind))
    dias = ctx.dias
    first = 21  # U
    dcol = {d: col(first + i) for i, d in enumerate(dias)}
    last_i = first + len(dias) - 1
    last = col(last_i)
    rem = col(last_i + 1)

    widths = {
        "A": 5, "B": 40, "C": 8, "D": 9, "E": 9, "F": 9, "G": 10, "H": 7.5, "I": 8, "J": 8.5,
        "K": 8.5, "L": 8.5, "M": 8.5, "N": 8, "O": 8, "P": 10, "Q": 11, "R": 8.5, "S": 10, "T": 10,
    }
    for d in dias:
        widths[dcol[d]] = 11.5
    widths[rem] = 58
    set_widths(ws, widths)

    # ---- rows 1-3: brand band (the reference leaves these rows for a stale header)
    merge(ws, f"A1:{rem}1",
          f"AVIGHNA   |   BAR BENDING SCHEDULE   |   {ctx.level or '-'}   |   {LOCATION_LABEL[kind]}",
          font=font(14, bold=True, color=WHITE), fill=fill(BRAND_RED), alignment=CENTER)
    merge(ws, f"A2:{rem}2",
          f"Generated by Avighna BOQ on {ctx.date_str}   |   Job {ctx.job.id}   |   "
          f"Prepared by {ctx.job.created_by_email or '-'}   |   Approved by {ctx.job.approved_by or '-'}",
          font=font(9, color="595959"), alignment=CENTER)
    set_heights(ws, {1: 24, 2: 15, 3: 8})

    _project_lines(ws, ctx, 4, rem)

    # ---- rows 7-8 info block
    info(ws, "A7:C7", "DRAWN BY :", alignment=LEFT)
    info(ws, "D7:F7", ctx.job.drawn_by or "-", bold=False)
    info(ws, "G7", "LD")
    info(ws, "H7", "Cover")
    info(ws, "I7:J7", "LOCATION")
    info(ws, "K7:T7", LOCATION_LABEL[kind], bold=False)
    info(ws, "U7:V7", "DRAWING REF :")
    info(ws, f"W7:{last}7", _refs(ctx), bold=False, alignment=LEFT, size=10)
    info(ws, "A8:C8", "Date :", alignment=LEFT)
    info(ws, "D8:F8", ctx.date_str, bold=False)
    cover = {"slab": ctx.std.cover_slab_mm, "wall": ctx.std.cover_wall_mm, "stair": ctx.std.cover_stair_mm}[kind]
    info(ws, "G8", ctx.std.ld_factor, number_format="0")
    info(ws, "H8", cover, number_format="0")
    info(ws, "I8:J8", "LEVEL")
    info(ws, "K8:T8", ctx.level or "-", bold=False)
    info(ws, "U8:V8", "Description")
    info(ws, f"W8:{last}8", f"{LOCATION_LABEL[kind]} Reinforcement", bold=False, size=10)
    info(ws, f"{rem}7:{rem}8", "Audit trail (engine trace)", bold=False, size=10)
    set_heights(ws, {7: 30, 8: 20})

    # ---- rows 9-10 column header (two-row, brand red)
    header(ws, "A9:A10", "Sr. No.")
    header(ws, "B9:B10", "MEMBER")
    header(ws, "C9:C10", "NO. of Members")
    size_label = {"slab": "Size Of Slab", "wall": "Size Of Wall", "stair": "Size Of Flight"}[kind]
    header(ws, "D9:F9", size_label)
    header(ws, "D10", "L")
    header(ws, "E10", "B")
    header(ws, "F10", "D")
    header(ws, "G9:G10", "Shape Of Bar")
    header(ws, "H9:H10", "Dia. Of Bar")
    for i, letter in enumerate("abcdefg"):
        header(ws, f"{col(9 + i)}9", letter)
    header(ws, "I10:O10", "LENGTH OF BARS")
    header(ws, "P9:P10", "Bend Deduction Corners")
    header(ws, "Q9:Q10", "Cut length Of One Bar")
    header(ws, "R9:R10", "Spacing (m)")
    header(ws, "S9:S10", "Bars per Member")
    header(ws, "T9:T10", "Total No.of Bars")
    header(ws, f"U9:{last}9", "WEIGHT CALCULATIONS")
    header(ws, f"U10:{last}10", "DIAMETERS")
    header(ws, f"{rem}9:{rem}10", AUDIT_HEADER)
    for d in dias:
        header(ws, f"{dcol[d]}11", d, number_format="0")
        put(ws, f"{dcol[d]}12", ctx.std.unit_weight(d), font=font(10, bold=True), fill=MID_FILL,
            border=BORDER_THIN, alignment=CENTER, number_format="0.000")
    merge(ws, "A11:T11", "Dia (mm)", font=font(9, color="595959"), alignment=RIGHT)
    merge(ws, "A12:T12", "Unit weight (kg/m)", font=font(9, color="595959"), alignment=RIGHT)
    set_heights(ws, {9: 30, 10: 30, 11: 18, 12: 18})

    # ---- data from row 13
    r = 13
    sr = 0
    for m in members:
        sr += 1
        hdr = r
        spec = ctx.spec_by_id.get(m.member_id)
        L, B, D = _dims(kind, spec)
        _member_header_style(ws, hdr, 1, last_i + 1)
        put(ws, f"A{hdr}", sr)
        put(ws, f"B{hdr}", m.tag, alignment=LEFT)
        put(ws, f"C{hdr}", m.nos)
        put(ws, f"D{hdr}", L, number_format=FMT_LEN)
        put(ws, f"E{hdr}", B, number_format=FMT_LEN)
        put(ws, f"F{hdr}", D, number_format=FMT_LEN)
        audit = " ; ".join(x for x in [_bars_summary(m), _warnings_text(m)] if x)
        _audit_cell(ws, f"{rem}{hdr}", audit)
        style_cells(ws, f"{rem}{hdr}", fill=PALE_FILL)
        r += 1
        for row in m.rows:
            _data_row_style(ws, r, 1, last_i + 1)
            put(ws, f"B{r}", row.description, alignment=LEFT)
            put(ws, f"G{r}", row.shape)
